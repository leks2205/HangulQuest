#!/usr/bin/env python3
"""Regenerate the quest tree report for the documentation.

Writes docs/book/src/quest-tree.md from the shipped questlines: totals, the goal and condition
breakdown, and one table per tree level. The file is committed, so readers can see the shape of the
tree on GitHub, and CI fails when it is out of date.

Usage:
    python3 tools/quest_tree.py [--check]

--check exits 1 when the committed report differs from what the content produces.
"""

from __future__ import annotations

import argparse
import collections
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "src/main/resources/assets/hangulquest/data/questlines")
OUT = os.path.join(ROOT, "docs/book/src/quest-tree.md")

GOAL_TEXT = {
    "BREAK_BLOCK": "break a block",
    "PLACE_BLOCK": "place a block",
    "ACQUIRE_ITEM": "collect an item",
    "CONSUME_ITEM": "eat or drink an item",
    "LOOK_AT_BLOCK": "look at a block",
    "LOOK_AT_ENTITY": "look at a mob",
    "DEFEAT_ENTITY": "defeat a mob",
    "REACH_BIOME": "reach a biome",
    "REACH_DIMENSION": "reach a dimension",
    "REACH_HEIGHT": "reach an altitude",
    "USE_BLOCK": "use a block",
    "INTERACT_ENTITY": "interact with a mob",
}

CONDITION_TEXT = {
    "TIME": "a time of day",
    "WEATHER": "the weather",
    "Y_RANGE": "an altitude band",
    "IN_BIOME": "a biome",
    "NEAR_ENTITY": "a mob nearby",
    "NEAR_BLOCK": "a block nearby",
    "IN_DIMENSION": "a dimension",
}


def load_trails() -> dict[str, dict]:
    trails: dict[str, dict] = {}
    for path in sorted(glob.glob(os.path.join(DATA, "*.json"))):
        name = os.path.basename(path)
        if name.startswith("_") or name == "index.json":
            continue
        with open(path, encoding="utf-8") as handle:
            trail = json.load(handle)
        trails[trail["id"]] = trail
    return trails


def depth_of(trail_id: str, trails: dict[str, dict], memo: dict[str, int]) -> int:
    if trail_id in memo:
        return memo[trail_id]
    parents = [parent for parent in (trails[trail_id]["requires"].get("completed") or []) if parent in trails]
    depth = 1 if not parents else 1 + max(depth_of(parent, trails, memo) for parent in parents)
    memo[trail_id] = depth
    return depth


def band_for(depth: int) -> int:
    """Mirrors Topik.levelForDepth in the mod."""
    for limit, band in ((3, 1), (6, 2), (9, 3), (12, 4), (15, 5)):
        if depth <= limit:
            return band
    return 6


def build() -> str:
    trails = load_trails()
    memo: dict[str, int] = {}
    depths = {trail_id: depth_of(trail_id, trails, memo) for trail_id in trails}

    goals: collections.Counter[str] = collections.Counter()
    conditions: collections.Counter[str] = collections.Counter()
    steps_total = 0
    for trail in trails.values():
        steps = list(trail["steps"]) + [trail["finale"]["step"]]
        steps_total += len(steps)
        for step in steps:
            goals[step["goal"]["type"]] += 1
            for condition in step.get("conditions", []):
                conditions[condition["type"]] += 1

    by_level: dict[int, list[dict]] = collections.defaultdict(list)
    for trail in trails.values():
        by_level[depths[trail["id"]]].append(trail)
    for level in by_level:
        by_level[level].sort(key=lambda trail: (trail["order"], trail["id"]))

    roots = sum(1 for trail in trails.values() if not trail["requires"].get("completed"))
    merges = sum(1 for trail in trails.values() if len(trail["requires"].get("completed") or []) > 1)

    lines: list[str] = []
    lines.append("# The quest tree")
    lines.append("")
    lines.append("<!-- Generated by tools/quest_tree.py from the shipped questlines. Do not edit by hand. -->")
    lines.append("")
    lines.append(
        "This page is generated from the content itself, so the numbers below are what the mod "
        "actually loads. Every trail is one JSON file in "
        "`src/main/resources/assets/hangulquest/data/questlines/`."
    )
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(f"| Questlines | **{len(trails)}** |")
    lines.append(f"| Steps (incl. finales) | **{steps_total}** |")
    lines.append(f"| Tree levels | **{max(by_level)}** |")
    lines.append(f"| Roots | {roots} |")
    lines.append(f"| Merges (more than one parent) | {merges} |")
    lines.append(
        "| Vocabulary | 293 curated concepts plus generated vanilla names and the Lute import |"
    )
    lines.append("")
    lines.append(
        "A trail's `koreanLevel` is the TOPIK band of its depth: levels 1–3 speak polite Korean, "
        "4–6 add obligation, 7–9 emphatic forms, 10–12 the double negative, 13–15 literary forms and "
        "16 and deeper the `-(으)ㄹ 수밖에 없어요` band."
    )
    lines.append("")

    lines.append("## Goals and conditions")
    lines.append("")
    lines.append("Every goal is checked on the client. Counts are per step, finales included.")
    lines.append("")
    lines.append("| Goal | Steps | What the player does |")
    lines.append("|---|---:|---|")
    for goal, count in goals.most_common():
        lines.append(f"| `{goal}` | {count} | {GOAL_TEXT.get(goal, '')} |")
    lines.append("")
    lines.append("| Condition | Steps | Must hold while the goal happens |")
    lines.append("|---|---:|---|")
    for condition, count in conditions.most_common():
        lines.append(f"| `{condition}` | {count} | {CONDITION_TEXT.get(condition, '')} |")
    lines.append("")

    lines.append("## Levels")
    lines.append("")
    for level in sorted(by_level):
        trails_at = by_level[level]
        lines.append(f"### Level {level} · TOPIK {band_for(level)} · {len(trails_at)} trails")
        lines.append("")
        lines.append("| Trail | Korean title | German title | Steps | Parents |")
        lines.append("|---|---|---|---:|---|")
        for trail in trails_at:
            parents = trail["requires"].get("completed") or []
            parent_text = ", ".join(f"`{parent}`" for parent in parents) if parents else "—"
            steps = len(trail["steps"]) + 1
            lines.append(
                f"| `{trail['id']}` | {trail['titleKo']} | {trail['titleDe']} | {steps} | {parent_text} |"
            )
        lines.append("")

    lines.append("## Reading the tree")
    lines.append("")
    lines.append(
        "- **Roots** have no `requires.completed`. There are several so a new player can start in the "
        "branch that matches what they are doing anyway."
    )
    lines.append(
        "- **Merges** (a trail with two or more parents) are the interesting nodes: they only unlock when "
        "every parent is finished, which is what turns a list of questlines into a tree."
    )
    lines.append(
        "- **Hints never leave level 1.** A late trail speaks literary Korean; pressing `H` restates the same "
        "task in polite Korean, so the ladder never blocks you."
    )
    lines.append(
        "- **The ritual finale is the guarantee.** Every trail ends with an action you can always perform — "
        "a torch at night, a campfire on a beach — never a structure or a coordinate."
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the report is out of date")
    args = parser.parse_args()

    report = build()
    if args.check:
        if not os.path.exists(OUT):
            print(f"{os.path.relpath(OUT, ROOT)} is missing", file=sys.stderr)
            return 1
        with open(OUT, encoding="utf-8") as handle:
            if handle.read() != report:
                print(
                    f"{os.path.relpath(OUT, ROOT)} is out of date: run python3 tools/quest_tree.py",
                    file=sys.stderr,
                )
                return 1
        print("quest tree report is up to date")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(report)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
