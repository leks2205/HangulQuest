	@Test
	void goldSetIsExact() throws IOException {
		JsonObject tags = tags();
		assertTrue(GOLD.size() >= 30, "the gold set shrank");
		List<String> problems = new ArrayList<>();
		for (Gold g : GOLD) {
			JsonObject tag = tags.getAsJsonObject(g.id());
			if (tag == null) {
				problems.add(g.id() + ": no tags");
				continue;
			}
			compare(problems, g.id(), "origin", g.origin(), tag.get("origin").getAsString());
			compare(problems, g.id(), "hanja", g.hanja(), hanja(tag));
			compare(problems, g.id(), "mcOnly", String.valueOf(g.mcOnly()), tag.get("mcOnly").getAsString());
			compare(problems, g.id(), "band", g.band(),
					tag.get("curriculumBand").isJsonNull() ? "" : tag.get("curriculumBand").getAsString());
			compare(problems, g.id(), "semSet", g.semSet(), tag.get("semSet").getAsString());
		}
		assertTrue(problems.isEmpty(), String.join("\n", problems));
	}

	private static void compare(List<String> problems, String id, String field, String expected, String actual) {
		if (!expected.equals(actual)) {
			problems.add(id + "." + field + ": expected '" + expected + "' but was '" + actual + "'");
		}
	}

	@Test
	void homophonesAreFlaggedAndCompoundsListTheirParts() throws IOException {
		JsonObject tags = tags();
		// 사과 (apple 沙果) vs 사과 (apology 謝過); 철 (iron 鐵) vs native 철 (season)
		assertTrue(tags.getAsJsonObject("apple").get("homophones").toString().contains("謝過"));
		assertTrue(tags.getAsJsonObject("iron").get("homophones").toString().contains("native"));
		Map<String, List<String>> parts = new LinkedHashMap<>();
		for (JsonElement p : tags.getAsJsonObject("gen_red_wool").getAsJsonArray("coreParts")) {
			parts.computeIfAbsent("gen_red_wool", k -> new ArrayList<>()).add(p.getAsJsonObject().get("word").getAsString());
		}
		assertEquals(List.of("빨간색", "양털"), parts.get("gen_red_wool"));
	}

	@Test
	void shareOfMinecraftOnlyWordsIsPlausible() throws IOException {
		int mc = 0;
		int all = 0;
		for (Map.Entry<String, JsonElement> entry : tags().entrySet()) {
			all++;
			if (entry.getValue().getAsJsonObject().get("mcOnly").getAsBoolean()) {
				mc++;
			}
		}
		// not a target, only a tripwire: a tagger bug that flags everything (or nothing) must show up here
		assertTrue(mc > all / 10 && mc < all * 3 / 4, mc + " of " + all);
	}
