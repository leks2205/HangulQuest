package io.github.leks2205.hangulquest.story;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import io.github.leks2205.hangulquest.dialogue.DialogueLexicon;
import io.github.leks2205.hangulquest.quest.JsonFields;
import io.github.leks2205.hangulquest.util.Lang;

import java.util.ArrayList;
import java.util.List;

/**
 * The words a story uses that the catalog does not have: pronouns, time words, connectors, a few verbs and
 * adjectives. {@code forms} are stems an eojeol may start with (the rest must be a particle, see
 * {@link StoryText#TAILS}); {@code verb} is a dictionary form whose conjugated forms are generated by the
 * {@code Conjugator}. {@code known} marks everyday words a beginner is expected to have met; {@code grammar}
 * names the construction a function word carries (안, 싶어요); {@code tails}, when given, limits the particles
 * the stem may take (the 안 that negates takes none, the 안 that means "inside" takes 에). The conversation
 * word list is read as well.
 */
public final class StoryLexicon {
	public static final StoryLexicon EMPTY = new StoryLexicon(List.of());

	public record Entry(String id, List<String> forms, List<String> tails, String verb, boolean known, String grammar,
						String en, String de) {
		public Entry {
			forms = List.copyOf(forms);
			tails = List.copyOf(tails);
			verb = verb == null ? "" : verb;
			grammar = grammar == null ? "" : grammar;
		}

		public boolean isVerb() {
			return !verb.isEmpty();
		}

		/** The gloss in the interface language: German for German, English for everything else. */
		public String gloss(Lang lang) {
			String text = lang == Lang.DE && !de.isBlank() ? de : en;
			return text.isBlank() ? de : text;
		}
	}

	private final List<Entry> entries;

	private StoryLexicon(List<Entry> entries) {
		this.entries = entries;
	}

	public static StoryLexicon parse(String json) {
		List<Entry> entries = new ArrayList<>();
		JsonObject root = JsonParser.parseString(json).getAsJsonObject();
		for (JsonElement element : root.getAsJsonArray("words")) {
			JsonObject word = element.getAsJsonObject();
			entries.add(new Entry(JsonFields.string(word, "id", ""), JsonFields.strings(word, "forms"),
					JsonFields.strings(word, "tails"), JsonFields.string(word, "verb", ""), word.has("known") && word.get("known").getAsBoolean(),
					JsonFields.string(word, "grammar", ""), JsonFields.string(word, "en", ""),
					JsonFields.string(word, "de", "")));
		}
		return new StoryLexicon(List.copyOf(entries));
	}

	/** This word list first, then the conversation list for the words it adds (the first entry of a form wins). */
	public StoryLexicon with(DialogueLexicon dialogue) {
		List<Entry> all = new ArrayList<>(entries);
		for (DialogueLexicon.Entry entry : dialogue.entries()) {
			all.add(new Entry("dialogue_" + entry.id(), entry.forms(), List.of(), "", entry.known(), "", entry.en(),
					entry.de()));
		}
		return new StoryLexicon(List.copyOf(all));
	}

	public List<Entry> entries() {
		return entries;
	}
}
